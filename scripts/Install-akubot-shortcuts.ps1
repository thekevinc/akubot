param(
    [string]$Distro = "Ubuntu",
    [string]$LinuxUser = "kc",
    [string]$ProjectPath = "/home/kc/workspace/akubot"
)
$ErrorActionPreference = "Stop"
# This installer runs on Windows. Application data stays in WSL.
foreach ($value in @($Distro, $LinuxUser, $ProjectPath)) {
    if ($value.Contains('"') -or $value.Contains("`r") -or $value.Contains("`n")) {
        throw "Shortcut arguments cannot contain quotes or newlines."
    }
}
$destination = Join-Path $env:LOCALAPPDATA "akubot\launcher"
New-Item -ItemType Directory -Path $destination -Force | Out-Null
$launcher = Join-Path $destination "Start-akubot.ps1"
$iconSource = Join-Path $PSScriptRoot "..\akubot\web\favicon.ico"
# A new name avoids stale Windows thumbnail-cache entries after an icon update.
$iconHash = (Get-FileHash -LiteralPath $iconSource -Algorithm SHA256).Hash.Substring(0, 12).ToLowerInvariant()
$icon = Join-Path $destination "akubot-$iconHash.ico"
Copy-Item -LiteralPath (Join-Path $PSScriptRoot "Start-akubot.ps1") -Destination $launcher -Force
Copy-Item -LiteralPath $iconSource -Destination $icon -Force
if (-not ("Akubot.ShortcutRefresh" -as [type])) {
    Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
using System.Text;
using Microsoft.Win32.SafeHandles;
namespace Akubot {
    public static class ShortcutRefresh {
        [DllImport("shell32.dll", CharSet = CharSet.Unicode)]
        public static extern void SHChangeNotify(uint eventId, uint flags, string item, IntPtr secondItem);
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
        public static extern uint GetFinalPathNameByHandle(SafeFileHandle file, StringBuilder path, uint length, uint flags);
    }
}
'@
}
# Compile a GUI executable with the bot picture embedded in its resources.
# This also gives Windows Start an identity separate from PowerShell.
$executable = Join-Path $destination "akubot.exe"
$source = Join-Path $PSScriptRoot "WindowsLauncher.cs"
$compiler = New-Object Microsoft.CSharp.CSharpCodeProvider
$parameters = New-Object System.CodeDom.Compiler.CompilerParameters
$parameters.GenerateExecutable = $true
$parameters.OutputAssembly = $executable
$parameters.CompilerOptions = '/target:winexe /win32icon:"{0}" /optimize+' -f $icon
foreach ($assembly in @("System.dll", "System.Core.dll", "System.Drawing.dll", "System.Windows.Forms.dll")) {
    $parameters.ReferencedAssemblies.Add($assembly) | Out-Null
}
$compiled = $compiler.CompileAssemblyFromSource($parameters, [IO.File]::ReadAllText($source))
$compiler.Dispose()
if ($compiled.Errors.HasErrors) {
    throw "The Windows launcher could not compile: $($compiled.Errors | ForEach-Object { $_.ErrorText })"
}
# Packaged Windows apps can redirect LocalAppData writes into their package.
# Explorer is outside that environment, so its links must use the physical path.
$stream = [IO.File]::OpenRead($executable)
try {
    $physicalPath = New-Object Text.StringBuilder 32768
    $length = [Akubot.ShortcutRefresh]::GetFinalPathNameByHandle($stream.SafeFileHandle, $physicalPath, $physicalPath.Capacity, 0)
    if ($length -eq 0 -or $length -ge $physicalPath.Capacity) { throw "Windows could not resolve the actual launcher path." }
    $executable = $physicalPath.ToString()
    if ($executable.StartsWith('\\?\UNC\')) { $executable = '\\' + $executable.Substring(8) }
    elseif ($executable.StartsWith('\\?\')) { $executable = $executable.Substring(4) }
    $destination = [IO.Path]::GetDirectoryName($executable)
} finally { $stream.Dispose() }
$arguments = '-Distro "{0}" -LinuxUser "{1}" -ProjectPath "{2}"' -f $Distro, $LinuxUser, $ProjectPath
$shell = New-Object -ComObject WScript.Shell
foreach ($folder in @([Environment]::GetFolderPath("Desktop"), [Environment]::GetFolderPath("Programs"))) {
    if (-not $folder) { throw "Windows could not locate the shortcut folder." }
    $shortcutPath = Join-Path $folder "akubot.lnk"
    # Recreate the link so the old autogenerated PowerShell identity is removed.
    if (Test-Path -LiteralPath $shortcutPath) { Remove-Item -LiteralPath $shortcutPath }
    $shortcut = $shell.CreateShortcut($shortcutPath)
    $shortcut.TargetPath = $executable
    $shortcut.Arguments = $arguments
    $shortcut.WorkingDirectory = $destination
    $shortcut.IconLocation = "$executable,0"
    $shortcut.Description = "Start akubot and open its local dashboard"
    $shortcut.Save()
    [Akubot.ShortcutRefresh]::SHChangeNotify(0x2000, 0x0005, $shortcutPath, [IntPtr]::Zero)
    Write-Host "Installed $shortcutPath"
}
